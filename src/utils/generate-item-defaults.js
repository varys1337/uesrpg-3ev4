/**
 * Generate canonical Item.system defaults from template.json.
 *
 * Node-only dev/build utility (NOT executed by Foundry).
 *
 * Usage:
 *   node utils/generate-item-defaults.js
 *
 * Output:
 *   src/core/migrations/item-defaults.generated.js
 */

const fs = require("node:fs/promises");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");

const TEMPLATE_PATH = path.join(repoRoot, "template.json");
const OUTPUT_PATH = path.join(repoRoot, "src", "core", "migrations", "item-defaults.generated.js");

// Non-breaking guardrails: paths that we must NOT apply from template defaults.
// Example: armor.item_cat is a mapping object in template.json, but runtime uses a string variant in some places.
const IGNORE_PATHS_BY_TYPE = {
  armor: ["item_cat"]
};

function isPlainObject(value) {
  if (!value || typeof value !== "object") return false;
  const proto = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

function deepClone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

function deepMerge(a, b) {
  const out = deepClone(a);
  for (const [k, v] of Object.entries(b)) {
    if (isPlainObject(out[k]) && isPlainObject(v)) out[k] = deepMerge(out[k], v);
    else out[k] = deepClone(v);
  }
  return out;
}

function buildDefaultsForType(itemModel, typeName) {
  const templates = itemModel.templates ?? {};
  const typeModel = itemModel[typeName];
  if (!typeModel) throw new Error(`Missing Item model for type: ${typeName}`);

  let merged = {};
  for (const templateName of (typeModel.templates ?? [])) {
    const t = templates[templateName];
    if (!t) throw new Error(`Missing Item.templates entry: ${templateName}`);
    merged = deepMerge(merged, t);
  }

  const typeBody = { ...typeModel };
  delete typeBody.templates;
  merged = deepMerge(merged, typeBody);
  return merged;
}

function jsModule(defaultsObj) {
  const objJson = JSON.stringify(defaultsObj, null, 2);
  return `/**
 * AUTO-GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Source: template.json (Item model)
 * Generated by: utils/generate-item-defaults.js
 *
 * This module exports canonical, template-derived defaults for Item.system payloads
 * for select item types used by migrations/normalizers.
 */
function deepFreeze(obj) {
  if (!obj || typeof obj !== "object") return obj;
  Object.freeze(obj);
  for (const value of Object.values(obj)) {
    if (value && typeof value === "object" && !Object.isFrozen(value)) deepFreeze(value);
  }
  return obj;
}

export const DEFAULTS = deepFreeze(
${objJson}
);
`;
}

async function main() {
  const raw = await fs.readFile(TEMPLATE_PATH, "utf8");
  const tpl = JSON.parse(raw);
  const itemModel = tpl?.Item;
  if (!itemModel) throw new Error("template.json missing top-level 'Item' model");

  const defaults = {
    itemSystem: {
      weapon: buildDefaultsForType(itemModel, "weapon"),
      armor: buildDefaultsForType(itemModel, "armor"),
      ammunition: buildDefaultsForType(itemModel, "ammunition")
    },
    __meta: {
      generatedFrom: "template.json#Item",
      ignorePathsByType: IGNORE_PATHS_BY_TYPE
    }
  };

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, jsModule(defaults), "utf8");
  console.log(`Wrote ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
